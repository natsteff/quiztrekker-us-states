"""Generate deterministic app icons and a subpath-scoped offline worker."""
import hashlib,json

def icons(root):
    # Raster variants are checked in so builds need no image tools or network.
    source=root.parent/'assets'
    for name in ('icon-192.png','icon-512.png','apple-touch-icon.png'):
        (root/name).write_bytes((source/name).read_bytes())

def worker(root):
    assets=sorted(p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file() and p.name not in ('sw.js','build.json'))
    version=hashlib.sha256(b''.join((root/name).read_bytes() for name in assets)).hexdigest()[:16]
    template='''// Generated by scripts/build.py. Scope is this project directory only.
const PREFIX='statequest:'+new URL('./',self.location.href).pathname+':';
const CACHE=PREFIX+'__VERSION__';
const ASSETS=__ASSETS__;
const BASE=new URL('./',self.location.href);
self.addEventListener('install',event=>{event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS)));});
self.addEventListener('message',event=>{if(event.data?.type==='SKIP_WAITING')event.waitUntil(self.skipWaiting());});
self.addEventListener('activate',event=>{event.waitUntil((async()=>{
 for(const name of await caches.keys())if(name.startsWith(PREFIX) && name!==CACHE)await caches.delete(name);
 await self.clients.claim();
})());});
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);
 if(event.request.method!=='GET' || url.origin!==BASE.origin || !url.pathname.startsWith(BASE.pathname))return;
 // Only cache bundled game files; never sibling GitHub Pages projects.
 const relative=url.pathname.slice(BASE.pathname.length);
 if(event.request.mode==='navigate' && (relative==='' || relative==='index.html')){
  event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match('./index.html'))||fetch(event.request)));return;
 }
 if(!ASSETS.includes('./'+relative))return;
 event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match('./'+relative))||fetch(event.request)));
});
'''
    (root/'sw.js').write_text(template.replace('__VERSION__',version).replace('__ASSETS__',json.dumps(['./'+a for a in assets])))
